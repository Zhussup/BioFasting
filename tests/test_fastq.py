# Fuzz: inputs nobody wrote by hand.
# --------------------------------------------------------------------------

ALPHABET = b"@+ACGT \t\r\n"


def reference_bytes(data: bytes):
    """The reference's verdict on raw bytes: records, or the exception."""
    from Bio.SeqIO.QualityIO import FastqGeneralIterator

    handle = io.StringIO(data.decode("ascii"), newline=None)
    try:
        return [
            (t.encode(), s.encode(), q.encode()) for t, s, q in FastqGeneralIterator(handle)
        ], None
    except ValueError as exc:
        return None, exc


@needs_biopython
@pytest.mark.parametrize("seed", range(8))
def test_random_input_gets_the_same_verdict(seed):
    """Random line-shaped text, both parsers, same answer.

    The generator is seeded and the alphabet is deliberately nasty: '@' and '+'
    are in it because they are the two characters that decide where a record
    ends, and so are spaces, tabs and both line endings.  Only ASCII is fed in,
    because the reference decodes and this kernel does not.
    """
    rng = random.Random(seed)
    for _ in range(300):
        lines = [
            bytes(rng.choice(ALPHABET) for _ in range(rng.randrange(0, 12)))
            for _ in range(rng.randrange(1, 14))
        ]
        data = b"\n".join(lines) + rng.choice([b"", b"\n"])
        expected, expected_error = reference_bytes(data)
        actual, actual_error = mine(data)
        assert (expected_error is None) == (actual_error is None), (
            f"seed={seed} data={data!r}\n"
            f"reference={expected_error!r}\nours={actual_error!r}"
        )
        assert actual == expected, f"seed={seed} data={data!r}"
