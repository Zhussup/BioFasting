GOOD_FASTQ = [
    "fastq/reads_10k.fastq",
    "edge/blank_lines.fastq",
    "edge/crlf.fastq",
    "edge/empty_file.fastq",
    "edge/empty_read.fastq",
    "edge/full_quality_range.fastq",
    "edge/long_read.fastq",
    "edge/multiline.fastq",
    "edge/no_trailing_newline.fastq",
    "edge/phred64.fastq",
    "edge/quality_contains_at_and_plus.fastq",
]

BAD_FASTQ = [
    "malformed/header_only.fastq",
    "malformed/length_mismatch.fastq",
    "malformed/missing_plus_line.fastq",
    "malformed/truncated_mid_quality.fastq",
]


@needs_biopython
@needs_corpus
@pytest.mark.parametrize("relative", GOOD_FASTQ)
def test_the_corpus_parses_identically(relative):
    path = DATA / relative
    expected, expected_error = reference(path)
    assert expected_error is None, f"the reference rejected {relative}"
    actual, actual_error = mine(path.read_bytes())
    assert actual_error is None
    assert actual == expected


@needs_biopython
@needs_corpus
@pytest.mark.parametrize("relative", BAD_FASTQ)
def test_the_corpus_is_rejected_by_both(relative):
    path = DATA / relative
    expected, expected_error = reference(path)
    actual, actual_error = mine(path.read_bytes())
    # Same verdict on every file: the reference refuses it, so this must too.
    assert (expected_error is None) == (actual_error is None), (
        f"{relative}: reference error={expected_error!r}, ours={actual_error!r}"
    )
    assert actual_error is not None


@needs_biopython
@needs_corpus
def test_the_million_read_corpus_parses_identically():
    """The file the benchmark actually measures, record for record.

    Not a speed test -- the numbers live in the bench.  This is the evidence
    that the fast path, which is the only path this file takes, returns the
    same bytes as the reference on all one million records.
    """
    from Bio.SeqIO.QualityIO import FastqGeneralIterator

    path = DATA / "fastq" / "reads_1m.fastq"
    scanner = biofasting.open_fastq(path)
    with open(path) as handle:
        expected_count = 0
        for expected in FastqGeneralIterator(handle):
            title, sequence, quality = next(scanner)
            assert title == expected[0].encode()
            assert sequence == expected[1].encode()
            assert quality == expected[2].encode()
            expected_count += 1
    assert expected_count == 1_000_000
    with pytest.raises(StopIteration):
        next(scanner)


@needs_biopython
@needs_corpus
def test_the_million_read_corpus_parses_identically_gzipped():
    """The same reads, compressed, through the inflate path.

    Diffed against the same reference the benchmark uses for a .gz row --
    `gzip.open()` in text mode -- so this covers the decompressor and the
    scanner together rather than the scanner twice.
    """
    from Bio.SeqIO.QualityIO import FastqGeneralIterator

    path = DATA / "fastq" / "reads_1m.fastq.gz"
    scanner = biofasting.open_fastq(path)
    with gzip.open(path, "rt") as handle:
        expected_count = 0
        for expected in FastqGeneralIterator(handle):
            title, sequence, quality = next(scanner)
            assert title == expected[0].encode()
            assert sequence == expected[1].encode()
            assert quality == expected[2].encode()
            expected_count += 1
    assert expected_count == 1_000_000
    with pytest.raises(StopIteration):
        next(scanner)


@needs_corpus
def test_the_gzipped_corpus_matches_the_plain_one():
    """The two corpus files are the same reads; this says so independently of
    the reference, so the gz evidence survives Biopython being unavailable."""
    plain = biofasting.open_fastq(DATA / "fastq" / "reads_10k.fastq")
    compressed = biofasting.open_fastq(DATA / "fastq" / "reads_1m.fastq.gz")
    for _, expected in zip(range(10_000), plain):
        assert next(compressed) == expected


